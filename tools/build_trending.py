# Fetch the channel's newest videos, keep those from the last 48h,
# rank by view count -> assets/js/trending.js  (used by the "Best Video" section)
# Usage: python tools/build_trending.py
import json, os, re, sys, time
from datetime import datetime, timezone, timedelta

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHANNEL = "https://www.youtube.com/@m3lomat-momt3a/videos"
FETCH_N = 40          # newest videos to inspect
TOP_N = 6             # how many to keep in trending.js
WINDOW_DAYS = 2       # "last 2 days"
FALLBACK_DAYS = 7     # widen window if nothing found

def main():
    import yt_dlp

    ids = [e["id"] for e in json.load(open(os.path.join(ROOT, "channel.json"), encoding="utf-8"))["entries"][:FETCH_N]]

    opts = {"quiet": True, "no_warnings": True, "skip_download": True,
            "extract_flat": False}
    vids = []
    with yt_dlp.YoutubeDL(opts) as ydl:
        for n, vid in enumerate(ids):
            try:
                info = ydl.extract_info("https://www.youtube.com/watch?v=" + vid, download=False)
            except Exception as e:
                print("skip", vid, str(e)[:80])
                continue
            vids.append({
                "id": vid,
                "t": info.get("title") or "",
                "v": info.get("view_count") or 0,
                "d": info.get("upload_date") or "",
                "dur": info.get("duration") or 0,
            })
            print(n + 1, "/", len(ids), vid, vids[-1]["d"], vids[-1]["v"])
            time.sleep(0.3)

    now = datetime.now(timezone.utc)
    def within(days, d):
        try:
            dt = datetime.strptime(d, "%Y%m%d").replace(tzinfo=timezone.utc)
        except ValueError:
            return False
        return (now - dt) <= timedelta(days=days)

    window = WINDOW_DAYS
    recent = [v for v in vids if within(window, v["d"])]
    if not recent:
        window = FALLBACK_DAYS
        recent = [v for v in vids if within(window, v["d"])]

    recent.sort(key=lambda v: -v["v"])
    top = recent[:TOP_N]

    data = {"window": window, "gen": now.strftime("%Y-%m-%d"), "vids": top}
    js = ("// Generated by tools/build_trending.py — do not edit by hand\n"
          "const TRENDING=" + json.dumps(data, ensure_ascii=False) + ";\n")
    dst = os.path.join(ROOT, "assets", "js", "trending.js")
    open(dst, "w", encoding="utf-8").write(js)
    print("wrote", dst, "| window:", window, "days | top:", len(top))

if __name__ == "__main__":
    main()
